async def send_message(
    client: AsyncClient, headers: dict[str, str], conversation_id: int, content: str = "Hi"
) -> None:
    response = await client.post(
        f"/conversations/{conversation_id}/messages", json={"content": content}, headers=headers
    )
    assert response.status_code == 200, response.text
    assert parse_sse(response.text)  # the stream completed


async def test_chat_without_persona_is_unchanged(
    client: AsyncClient, scripted_provider: ScriptedProvider
) -> None:
    """No persona → the character prompt reaches the model exactly as before."""
    headers, _user = await auth_user(client, "alice")
    conversation = await create_conversation(client, headers)

    await send_message(client, headers, conversation["id"])

    system = scripted_provider.requests[0].messages[0]
    assert system.role == "system"
    assert system.content == (
        "You are Maya, a friendly and helpful assistant.\n\n" + MESSAGE_FORMAT_HINT
    )
    assert PERSONA_HEADER not in system.content


async def test_chat_with_persona_includes_it_in_the_system_context(
    client: AsyncClient, scripted_provider: ScriptedProvider
) -> None:
    headers, _user = await auth_user(client, "alice")
    persona = await create_persona(
        client,
        headers,
        name="Alex",
        gender="male",
        age=25,
        description="A software engineer who enjoys programming.",
    )
    conversation = await create_conversation(client, headers, user_persona_id=persona["id"])

    await send_message(client, headers, conversation["id"])

    request = scripted_provider.requests[0]
    system = request.messages[0]
    assert system.role == "system"
    # Character prompt first, persona appended as system-level context.
    assert system.content.startswith("You are Maya, a friendly and helpful assistant.")
    assert PERSONA_HEADER in system.content
    block = system.content.split(PERSONA_HEADER)[1].split(PERSONA_FOOTER)[0]
    assert block.strip().splitlines() == [
        "Name: Alex",
        "Gender: male",
        "Age: 25",
        "Description: A software engineer who enjoys programming.",
    ]
    # The persona is never sent as a user message.
    assert [m.role for m in request.messages[1:]] == ["user"]
    assert json.loads(request.messages[-1].content)["content"] == "Hi"


