async def test_create_persona_owner_comes_from_the_token(
    client: AsyncClient, session_factory: Any
) -> None:
    """A user_id in the body cannot choose the owner."""
    _headers_a, alice = await auth_user(client, "alice")
    headers_b, bob = await auth_user(client, "bob")

    response = await client.post(
        "/personas",
        json={"name": "Impostor", "user_id": alice["id"], "id": 999},
        headers=headers_b,
    )

    assert response.status_code == 201, response.text
    persona = response.json()
    assert persona["user_id"] == bob["id"]
    assert persona["id"] != 999

    async with session_factory() as db:
        row = (await db.scalars(select(UserPersona).where(UserPersona.id == persona["id"]))).first()
    assert row is not None
    assert row.user_id == bob["id"]

    # Alice's persona list stays empty.
    response = await client.get("/personas", headers=_headers_a)
    assert response.json() == []


async def test_create_persona_validation(client: AsyncClient) -> None:
    headers, _user = await auth_user(client, "alice")

    invalid: list[dict[str, Any]] = [
        {},  # name is required
        {"name": ""},  # not blank
        {"name": "x" * 101},  # NAME VARCHAR2(100)
        {"name": "ok", "gender": "x" * 11},  # GENDER VARCHAR2(10)
        {"name": "ok", "description": "d" * 501},  # DESCRIPTION VARCHAR2(500)
        {"name": "ok", "age": 100},  # AGE NUMBER(2,0)
        {"name": "ok", "age": -1},
    ]
    for body in invalid:
        response = await client.post("/personas", json=body, headers=headers)
        assert response.status_code == 422, (body, response.text)

    # Explicit nulls for the optional columns are accepted.
    response = await client.post(
        "/personas",
        json={"name": "Nulls", "gender": None, "description": None, "age": None},
        headers=headers,
    )
    assert response.status_code == 201, response.text


