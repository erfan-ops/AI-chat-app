# -- Persona privacy ------------------------------------------------------------------


async def test_personas_are_private(client: AsyncClient) -> None:
    headers_alice, _alice = await auth_user(client, "alice")
    headers_bob, _bob = await auth_user(client, "bob")
    bob_persona = await create_persona(client, headers_bob, name="Bob's Alex")

    # Alice cannot read, modify or delete it — 404, as if it did not exist.
    for method, kwargs in (
        ("get", {}),
        ("patch", {"json": {"name": "stolen"}}),
        ("delete", {}),
    ):
        response = await getattr(client, method)(
            f"/personas/{bob_persona['id']}", headers=headers_alice, **kwargs
        )
        assert response.status_code == 404, (method, response.text)
        assert response.json() == {"detail": "Persona not found"}

    # Nor does it appear in her list; Bob's is untouched.
    assert (await client.get("/personas", headers=headers_alice)).json() == []
    response = await client.get(f"/personas/{bob_persona['id']}", headers=headers_bob)
    assert response.json()["name"] == "Bob's Alex"


async def test_admins_get_no_special_persona_access(
    client: AsyncClient, session_factory: Any
) -> None:
    """Personas are personal data — the admin role does not widen access."""
