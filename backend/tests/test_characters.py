async def test_create_character_validation(client: AsyncClient) -> None:
    headers, _user = await auth_user(client, "alice")

    invalid_bodies: list[dict[str, Any]] = [
        {},  # name is required
        {"name": ""},  # name must not be blank
        {"name": "x" * 101},  # NAME VARCHAR2(100)
        {"name": "ok", "description": "d" * 501},  # DESCRIPTION VARCHAR2(500)
        {"name": "ok", "avatar_url": "u" * 1001},  # AVATAR_URL VARCHAR2(1000)
        {"name": "ok", "system_prompt": "p" * 9001},  # SYSTEM_PROMPT VARCHAR2(9000)
    ]
    for body in invalid_bodies:
        response = await client.post("/characters", json=body, headers=headers)
        assert response.status_code == 422, (body, response.text)

    # The boundary values themselves are accepted.
    response = await client.post(
        "/characters",
        json={
            "name": "x" * 100,
            "description": "d" * 500,
            "avatar_url": "u" * 1000,
            "system_prompt": "p" * 9000,
        },
        headers=headers,
    )
    assert response.status_code == 201, response.text


async def test_list_characters_hides_other_users_characters(client: AsyncClient) -> None:
    headers_a, user_a = await auth_user(client, "alice")
    headers_b, _user_b = await auth_user(client, "bob")

    await create_character(client, headers_a, name="Alice's Nova")
    await create_character(client, headers_b, name="Bob's Rex")

    response = await client.get("/characters", headers=headers_a)
    assert response.status_code == 200
    characters = response.json()
    # Built-in character + Alice's own, never Bob's.
    assert [c["name"] for c in characters] == ["Maya", "Alice's Nova"]
    assert [c["owner_user_id"] for c in characters] == [None, user_a["id"]]


async def test_get_other_users_character_is_not_found(client: AsyncClient) -> None:
    headers_a, _user_a = await auth_user(client, "alice")
    headers_b, _user_b = await auth_user(client, "bob")

    bob_character = await create_character(client, headers_b, name="Bob's Rex")

    response = await client.get(f"/characters/{bob_character['id']}", headers=headers_a)
    assert response.status_code == 404
    assert response.json() == {"detail": "Character not found"}

    # Bob still sees his own, and both users see the built-in one.
    response = await client.get(f"/characters/{bob_character['id']}", headers=headers_b)
    assert response.status_code == 200
    for headers in (headers_a, headers_b):
        response = await client.get(f"/characters/{BUILTIN_CHARACTER_ID}", headers=headers)
        assert response.status_code == 200


async def test_conversation_with_another_users_character_is_rejected(client: AsyncClient) -> None:
    headers_a, _user_a = await auth_user(client, "alice")
    headers_b, _user_b = await auth_user(client, "bob")

    bob_character = await create_character(client, headers_b, name="Bob's Rex")

    response = await client.post(
        "/conversations", json={"character_id": bob_character["id"]}, headers=headers_a
    )
    assert response.status_code == 404
    assert response.json() == {"detail": "Character not found"}

    # Bob can start a conversation with his own character.
    response = await client.post(
        "/conversations", json={"character_id": bob_character["id"]}, headers=headers_b
    )
    assert response.status_code == 201, response.text
    assert response.json()["character"]["id"] == bob_character["id"]
