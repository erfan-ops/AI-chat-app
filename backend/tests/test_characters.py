async def test_create_character_owner_comes_from_the_token(
    client: AsyncClient, session_factory: Any
) -> None:
    """The owner is the authenticated user, and immutable columns are never assignable.

    A non-admin who *sends* owner_user_id is rejected outright — see
    ``tests/test_admin.py::test_regular_user_cannot_use_admin_fields``.
    """
    headers_a, _user_a = await auth_user(client, "alice")
    headers_b, user_b = await auth_user(client, "bob")

    response = await client.post(
        "/characters",
        json={"name": "Impostor", "id": 999, "created_at": "1999-01-01T00:00:00Z"},
        headers=headers_b,
    )

    assert response.status_code == 201, response.text
    character = response.json()
    assert character["owner_user_id"] == user_b["id"]
    assert character["id"] != 999
    assert not character["created_at"].startswith("1999")

    async with session_factory() as db:
        row = (await db.scalars(select(Character).where(Character.id == character["id"]))).first()
    assert row is not None
    assert row.owner_user_id == user_b["id"]
    assert row.status == "ACTIVE"

    # Alice does not gain a character she never created.
    response = await client.get("/characters", headers=headers_a)
    assert [c["name"] for c in response.json()] == ["Maya"]


