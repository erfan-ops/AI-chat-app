"""Character catalog tests: creation, ownership, and cross-user visibility.

Character 1 ("Maya", ``OWNER_USER_ID IS NULL``) is seeded by the ``catalog``
fixture and stands in for a built-in character.
"""

from __future__ import annotations

from typing import Any

from httpx import AsyncClient
from sqlalchemy import select

from app.db.models.character import Character
from tests.conftest import auth_user, create_character

BUILTIN_CHARACTER_ID = 1


async def test_create_character(client: AsyncClient, session_factory: Any) -> None:
    headers, user = await auth_user(client, "alice")

    character = await create_character(
        client,
        headers,
        name="Nova",
        description="A calm, curious assistant.",
        avatar_url="https://example.com/nova.png",
        system_prompt="You are Nova, calm and curious.",
    )

    assert isinstance(character["id"], int)  # identity-generated by the database
    assert character["id"] != BUILTIN_CHARACTER_ID
    assert character["name"] == "Nova"
    assert character["description"] == "A calm, curious assistant."
    assert character["avatar_url"] == "https://example.com/nova.png"
    assert character["system_prompt"] == "You are Nova, calm and curious."
    assert character["owner_user_id"] == user["id"]
    assert character["created_at"] is not None

    async with session_factory() as db:
        row = (await db.scalars(select(Character).where(Character.id == character["id"]))).first()
    assert row is not None
    assert row.owner_user_id == user["id"]
    assert row.status == "ACTIVE"
    assert row.created_at is not None
    assert row.updated_at is not None


